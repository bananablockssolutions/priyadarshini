/* Mobile menu flow (approved prototype, 19 Nov): dropping border, row grows into the type page, Back, list view, filters, reduced motion, no JavaScript. Needs dev/seed-demo.php. Run: PD_URL=http://127.0.0.1:8088 node dev/tests/menu_e2e.js */
const { chromium } = require('playwright');
const B=process.env.PD_URL||'http://127.0.0.1:8088', O=process.env.PD_SHOTS||'/tmp/';
(async()=>{
 const br=await chromium.launch(); const res=[]; const ok=(n,c)=>res.push((c?'PASS ':'FAIL ')+n);
 let ctx=await br.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
 let p=await ctx.newPage(); const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>m.type()==='error'&&errs.push(m.text()));
 await p.goto(B+'/?pd-nosplash'); await p.waitForTimeout(800);
 await p.screenshot({path:O+'0-home.png'});
 ok('bottom bar visible', await p.isVisible('.pd-tabs'));
 ok('home tab current', (await p.getAttribute('.pd-tabs a:nth-child(1)','aria-current'))==='page');
 await p.tap('#pd-shell-menu-btn');
 await p.waitForTimeout(250); await p.screenshot({path:O+'1-drop.png'});
 await p.waitForTimeout(900); await p.screenshot({path:O+'2-menu.png'});
 ok('menu open', await p.isVisible('#pd-menu'));
 ok('aria-expanded', (await p.getAttribute('#pd-shell-menu-btn','aria-expanded'))==='true');
 ok('5 rows', (await p.locator('.pd-mrow').count())===5);
 await p.tap('.pd-mrow[href*="/kurti/"]');
 await p.waitForTimeout(180); await p.screenshot({path:O+'3-leave.png'});
 await p.waitForTimeout(260); await p.screenshot({path:O+'4-grow.png'});
 await p.waitForTimeout(250); await p.screenshot({path:O+'5-grow2.png'});
 await p.waitForTimeout(1300); await p.screenshot({path:O+'6-page.png'});
 ok('url kurti', p.url().includes('/kurti/'));
 ok('h1 Kurti', (await p.textContent('#pd-main h1')).includes('Kurti'));
 ok('focus h1', await p.evaluate(()=>document.activeElement?.tagName==='H1'));
 ok('menu closed', !(await p.isVisible('#pd-menu')));
 ok('no fly copies left', (await p.locator('.pd-fly').count())===0);
 ok('cards visible', await p.evaluate(()=>[...document.querySelectorAll('.pd-shop .wc-block-product-template > li')].every(li=>getComputedStyle(li).opacity==='1')));
 ok('explore tab current', (await p.getAttribute('.pd-tabs a:nth-child(2)','aria-current'))==='page');
 await p.tap('.pd-toolbar__views button:nth-child(2)'); await p.waitForTimeout(500); await p.screenshot({path:O+'7-list.png'});
 ok('list view', await p.evaluate(()=>document.documentElement.dataset.pdView==='list'));
 await p.tap('.pd-toolbar__views button:nth-child(1)'); await p.waitForTimeout(400);
 await p.tap('.pd-rail'); await p.waitForTimeout(400); await p.screenshot({path:O+'8-filters.png'});
 ok('filters sheet', await p.isVisible('.pd-sheet.is-open'));
 await p.keyboard.press('Escape'); await p.waitForTimeout(350);
 await p.goBack(); await p.waitForTimeout(250); await p.screenshot({path:O+'9-back-mid.png'}); await p.waitForTimeout(900); await p.screenshot({path:O+'10-back.png'});
 ok('back home', new URL(p.url()).pathname==='/');
 ok('back: menu open', await p.isVisible('#pd-menu'));
 ok('back: focus row', await p.evaluate(()=>document.activeElement?.classList.contains('pd-mrow')));
 ok('back: no copies', (await p.locator('.pd-fly').count())===0);
 await p.tap('#pd-shell-menu-btn'); await p.waitForTimeout(900);
 ok('X closes', !(await p.isVisible('#pd-menu')));
 ok('no js errors', errs.length===0); if(errs.length) console.log(errs.slice(0,5));
 await ctx.close();
 ctx=await br.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'}); p=await ctx.newPage();
 await p.goto(B+'/?pd-nosplash'); await p.click('#pd-shell-menu-btn'); await p.waitForTimeout(100);
 ok('reduced: menu open at once', await p.isVisible('#pd-menu'));
 await p.click('.pd-mrow[href*="/saree/"]'); await p.waitForTimeout(1200);
 ok('reduced: saree page', (await p.textContent('#pd-main h1')).includes('Saree'));
 await ctx.close();
 ctx=await br.newContext({viewport:{width:390,height:844},javaScriptEnabled:false}); p=await ctx.newPage();
 await p.goto(B+'/?pd-nosplash'); await p.click('#pd-shell-menu-btn');
 ok('nojs: menu', await p.isVisible('#pd-menu'));
 await p.click('.pd-mrow[href*="/dupatta/"]'); ok('nojs: page', (await p.textContent('h1')).includes('Dupatta'));
 await ctx.close(); await br.close(); console.log(res.join('\n'));
})();
